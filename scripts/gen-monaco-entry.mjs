// Generates src/renderer/monaco/monaco-lite.js: monaco-editor's editor.main.js with every
// editor contribution but only the JSON language (no TypeScript/CSS/HTML workers ≈ 17 MB less).
// Re-run after upgrading monaco-editor:  node scripts/gen-monaco-entry.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = join(root, 'node_modules/monaco-editor')
const main = readFileSync(join(pkg, 'esm/vs/editor/editor.main.js'), 'utf8')
const rewrite = (p) => p.replace(/^\.\.\//, 'monaco-esm/').replace(/^\.\//, 'monaco-esm/editor/')

const out = ['// GENERATED by scripts/gen-monaco-entry.mjs — do not edit.']
for (const line of main.split('\n')) {
  const side = /^import '([^']+)';$/.exec(line)
  if (side) {
    const p = side[1]
    if (p.includes('languages/definitions/') && !p.includes('/json/')) continue
    out.push(`import '${rewrite(p)}'`)
    continue
  }
  const ns = /^import \* as (\w+) from '([^']+)';$/.exec(line)
  if (ns) {
    if (ns[2].includes('features/json/')) out.push(`import * as ${ns[1]} from '${rewrite(ns[2])}'`)
    continue
  }
  const ex = /^export \{ (\w+) as json \};$/.exec(line)
  if (ex) {
    out.push(`export { ${ex[1]} as json }`)
    continue
  }
  const api = /^export \{ (.+) \} from '\.\/editor\.api\.js';$/.exec(line)
  if (api) out.push(`export { ${api[1]} } from 'monaco-esm/editor/editor.api.js'`)
}
const file = join(root, 'src/renderer/monaco/monaco-lite.js')
writeFileSync(file, out.join('\n') + '\n')
console.log(`wrote ${file} (${out.length} lines)`)
